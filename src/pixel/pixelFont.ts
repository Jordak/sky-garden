export function measurePixelText(text: string): number {
  const upper = text.toUpperCase();
  let width = 0;
  for (let i = 0; i < upper.length; i += 1) {
    const ch = upper[i];
    if (ch === ' ') {
      width += 3;
    } else {
      const g = GLYPHS[ch];
      width += (g ? g[0].length : 3) + 1;
    }
  }
  return Math.max(0, width - 1);
}

export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  startX: number,
  startY: number,
  color: string,
  shadowColor?: string,
): void {
  const upper = text.toUpperCase();
  const x0 = Math.round(startX);
  const y0 = Math.round(startY);

  if (shadowColor) {
    drawPixelText(ctx, upper, x0, y0 + 1, shadowColor);
  }

  ctx.fillStyle = color;
  let cursorX = x0;

  for (let i = 0; i < upper.length; i += 1) {
    const ch = upper[i];
    if (ch === ' ') {
      cursorX += 3;
      continue;
    }
    const rows = GLYPHS[ch];
    if (rows) {
      const gw = rows[0].length;
      for (let r = 0; r < rows.length; r += 1) {
        const row = rows[r];
        for (let c = 0; c < gw; c += 1) {
          if (row[c] === '#') {
            ctx.fillRect(cursorX + c, y0 + r, 1, 1);
          }
        }
      }
      cursorX += gw + 1;
    } else {
      cursorX += 4;
    }
  }
}
